const require = createRequire(import.meta.url);
const { PDFParse } = require('pdf-parse');

const RAW_DIR = path.resolve(process.cwd(), 'docs/sources/raw');
const OUT_FILE = path.resolve(process.cwd(), 'docs/sources/ingest-report.md');

async function getIngestParsers() {
  const d1Url = pathToFileURL(path.resolve(process.cwd(), 'scripts/ingest-drugceiling1.ts')).href;
  const d2Url = pathToFileURL(path.resolve(process.cwd(), 'scripts/ingest-drugceiling2.ts')).href;
  const d3Url = pathToFileURL(path.resolve(process.cwd(), 'scripts/ingest-drugceiling3.ts')).href;

  const [d1Mod, d2Mod, d3Mod] = await Promise.all([
    import(d1Url),
    import(d2Url),
    import(d3Url),
  ]);

  return {
    parseDrugceiling1: d1Mod.parseDrugceiling1,
    parseDrugceiling2: d2Mod.parseDrugceiling2,
    parseDrugceiling3: d3Mod.parseDrugceiling3,
  };
}

interface FileEvidence {
  filename: string;
  sha256: string;
  sizeBytes: number;
  pageCount: number;
  instrumentNumber: string;
  instrumentDate: string;
  effectiveDate: string;
  totalParsedRows: number;
  pageRowCounts: Record<number, number>;
  records: Array<{
    id: string;
    page: number;
    slNo: number | string;
    rawLines: string[];
    parsed: Record<string, any>;
  }>;
  notes?: string[];
}

async function extractRawPdfPages(filePath: string): Promise<Array<{ pageNum: number; text: string }>> {
  const buf = fs.readFileSync(filePath);
  const parser = new PDFParse({ data: buf });
  await parser.load();
  const pdfData = await parser.getText();
  const pages: Array<{ pageNum: number; text: string }> = (pdfData.pages || []).map((p: any) => ({
    pageNum: p.num,
    text: p.text || '',
  }));
  await parser.destroy();
  return pages;
}

function getFileMeta(filename: string) {
  const filePath = path.join(RAW_DIR, filename);
  const buf = fs.readFileSync(filePath);
  const sha256 = crypto.createHash('sha256').update(buf).digest('hex');
  const stat = fs.statSync(filePath);
  return { filePath, sha256, sizeBytes: stat.size };
}

